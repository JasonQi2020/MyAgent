"""Build the VM's configuration from the laptop's (design/deployment.md §6, §6.1).

    python3 deploy/make_vm_env.py OUT_DIR

Writes OUT_DIR/.env, OUT_DIR/agent.properties and OUT_DIR/state/ (Feishu and WeCom only),
all mode 600. Prints key names only: no secret value is ever shown.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VM_ROOT = "/srv/agents/agent-demo"
VM_CHANNELS = ("feishu", "wecom")

# .env keys the VM needs (exact names or prefixes ending in "_"); everything else stays on the laptop.
KEEP = ("LLM_", "DASHSCOPE_", "DB_PATH", "MAX_STEPS", "MCP_CONFIG", "SINA_", "FEISHU_", "WECOM_")
SET_ENV = {"IM_CHANNELS": ",".join(VM_CHANNELS)}
SET_PROPERTIES = {
    "claude.enabled": "false",  # Anthropic refuses the region
    "claude.folders": f"{VM_ROOT}/data",
    "tasks.timezone": "America/Vancouver",
}

_LINE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*=(.*)$")


def keep(key: str) -> bool:
    return any(key.startswith(k) if k.endswith("_") else key == k for k in KEEP)


def private_file(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


def build_env(source: Path) -> tuple[str, list[str], list[str]]:
    kept, dropped, lines = [], [], ["# agent-demo on the VM: generated by deploy/make_vm_env.py from the laptop's .env\n"]
    for raw in source.read_text(encoding="utf-8").splitlines():
        m = _LINE.match(raw)
        if not m or m[1] in SET_ENV:
            continue
        if keep(m[1]):
            kept.append(m[1])
            lines.append(f"{m[1]}={m[2].strip()}\n")
        else:
            dropped.append(m[1])
    lines += [f"{k}={v}\n" for k, v in SET_ENV.items()]
    return "".join(lines), kept + list(SET_ENV), dropped


def build_properties(source: Path) -> str:
    out, done = [], set()
    for raw in source.read_text(encoding="utf-8").splitlines():
        m = _LINE.match(raw)
        if m and m[1] in SET_PROPERTIES:
            out += ["# Set for the VM by deploy/make_vm_env.py", f"{m[1]}={SET_PROPERTIES[m[1]]}"]
            done.add(m[1])
        else:
            out.append(raw)
    out += [f"{k}={v}" for k, v in SET_PROPERTIES.items() if k not in done]
    return "\n".join(out) + "\n"


def build_state(source: Path, out: Path) -> list[str]:
    copied = []
    owners = source / "owner_chats.json"
    if owners.exists():
        data = {c: v for c, v in json.loads(owners.read_text(encoding="utf-8")).items() if c in VM_CHANNELS}
        private_file(out / "owner_chats.json", json.dumps(data, indent=2) + "\n")
        copied.append(f"owner_chats.json ({', '.join(data) or 'empty'})")
    groups = source / "im_groups.json"
    if groups.exists():
        data = {c: g for c, g in json.loads(groups.read_text(encoding="utf-8")).items() if c in VM_CHANNELS}
        private_file(out / "im_groups.json", json.dumps(data, indent=2) + "\n")
        copied.append(f"im_groups.json ({sum(len(g) for g in data.values())} groups)")
    tasks = source / "tasks.db"
    if tasks.exists():
        target = out / "tasks.db"
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        with sqlite3.connect(tasks) as src, sqlite3.connect(target) as dst:
            src.backup(dst)  # a consistent copy even if the laptop server is running
            marks = ",".join("?" * len(VM_CHANNELS))
            dst.execute(f"DELETE FROM tasks WHERE channel NOT IN ({marks})", VM_CHANNELS)
            count = dst.execute("SELECT count(*) FROM tasks").fetchone()[0]
        target.chmod(0o600)
        copied.append(f"tasks.db ({count} Feishu/WeCom tasks)")
    return copied


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    out = Path(argv[1])
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True, mode=0o700)
    env, kept, dropped = build_env(ROOT / ".env")
    private_file(out / ".env", env)
    private_file(out / "agent.properties", build_properties(ROOT / "agent.properties"))
    state = build_state(ROOT / "state", out / "state")
    print(f".env: {len(kept)} keys: {', '.join(kept)}")
    print(f"      left on the laptop: {', '.join(dropped) or 'none'}")
    print(f"agent.properties: {', '.join(f'{k}={v}' for k, v in SET_PROPERTIES.items())}")
    print(f"state/: {'; '.join(state) or 'nothing'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
